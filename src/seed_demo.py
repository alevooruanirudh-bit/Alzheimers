"""
Seed demo Digital Twins:  python -m src.seed_demo

Loads a few real TEST-set patients (no fitting, just inference) into the
database as demo twins: up to three from each risk level. Three of
them also get SIMULATED follow-up visits so the risk-trend chart can be
demonstrated. Simulated visits are flagged `is_simulated=True` in the
database and labelled "Simulated demo visit" in the UI. They are not real
patient data.
"""
from datetime import datetime, timedelta

import numpy as np

from src import config
from src.data import get_test, get_test_original_index
from src.predictor import RiskPredictor
from src.twin import SessionLocal, create_patient, init_db, record_visit

SIM_NOTE = "SIMULATED DEMO VISIT - generated by seed_demo.py, not real patient data"


def clip(name: str, v: float) -> float:
    from src.schema import FIELD_BY_NAME
    f = FIELD_BY_NAME[name]
    return float(np.clip(round(v, 2), f["min"], f["max"]))


def simulate(base: dict, scenario: str, step: int) -> dict:
    """Make a plausible follow-up visit from a baseline (demo only)."""
    v = dict(base)
    if scenario == "decline":       # gradual cognitive/functional decline
        v["MMSE"] = clip("MMSE", base["MMSE"] - 3.5 * step)
        v["FunctionalAssessment"] = clip("FunctionalAssessment", base["FunctionalAssessment"] - 1.4 * step)
        v["ADL"] = clip("ADL", base["ADL"] - 1.2 * step)
        if step >= 2:
            v["MemoryComplaints"] = 1
    elif scenario == "improve":     # lifestyle and functional improvement
        v["PhysicalActivity"] = clip("PhysicalActivity", base["PhysicalActivity"] + 2.0 * step)
        v["SleepQuality"] = clip("SleepQuality", base["SleepQuality"] + 0.8 * step)
        v["DietQuality"] = clip("DietQuality", base["DietQuality"] + 1.5 * step)
        v["FunctionalAssessment"] = clip("FunctionalAssessment", base["FunctionalAssessment"] + 1.3 * step)
        v["ADL"] = clip("ADL", base["ADL"] + 1.3 * step)
        v["MMSE"] = clip("MMSE", base["MMSE"] + 1.5 * step)
    elif scenario == "stable":      # small fluctuations only
        v["MMSE"] = clip("MMSE", base["MMSE"] + (0.6 if step % 2 else -0.4))
        v["SystolicBP"] = clip("SystolicBP", base["SystolicBP"] - 4 * step)
    v["Age"] = clip("Age", base["Age"] + 0.5 * step)  # six-monthly visits
    return v


def main() -> None:
    init_db(reset=True)
    predictor = RiskPredictor()
    X, y = get_test()
    orig = get_test_original_index()
    probs = predictor.hybrid.predict_proba(X)
    levels = np.array([config.risk_level(p) for p in probs])

    chosen = []  # deterministic pick: up to three patients per risk level, spread over the range
    for level in ("Low", "Medium", "High"):
        idx = np.flatnonzero(levels == level)
        if len(idx):
            chosen += list(idx[np.linspace(0, len(idx) - 1, min(3, len(idx))).astype(int)])
    # decline: a low-risk patient; stable: another low-risk patient; improve: a high-risk patient
    # (the improving patient is the chosen high-risk patient with the highest MMSE)
    high = [i for i in chosen if levels[i] == "High"] or chosen
    improver = max(high, key=lambda i: X.iloc[i]["MMSE"])
    scenarios = {chosen[0]: "decline", chosen[1]: "stable", improver: "improve"}

    start = datetime(2025, 1, 15, 10, 0)
    with SessionLocal() as s:
        for n, i in enumerate(chosen, start=1):
            inputs = {k: float(v) for k, v in X.iloc[i].items()}
            p = create_patient(s, f"Demo patient {n:02d}", inputs, is_demo=True,
                               source=f"Kaggle test set (CSV row {orig[i]})", dataset_label=int(y.iloc[i]))
            record_visit(s, p, inputs, predictor, recorded_at=start, kind="clinical",
                         note="Baseline: real record from the held-out test set")
            if i in scenarios:
                for step in (1, 2, 3):
                    record_visit(s, p, simulate(inputs, scenarios[i], step), predictor, kind="clinical",
                                 recorded_at=start + timedelta(days=182 * step), is_simulated=True,
                                 note=f"{SIM_NOTE} ({scenarios[i]} scenario)")
            last = p.latest_prediction
            print(f"  {p.name}: {last.risk_level:6s} {last.probability:6.1%}  "
                  f"visits={len(p.observations)}  {'(+ simulated follow-ups)' if i in scenarios else ''}")
        s.commit()
    print(f"Seeded {len(chosen)} demo twins into {config.DATABASE_URL}")
    from src.accounts import ensure_demo_accounts, ensure_profiles
    with SessionLocal() as s:
        ensure_profiles(s)
        print("Demo accounts:", ensure_demo_accounts(s), "(see src/accounts.py for passwords)")
        s.commit()


if __name__ == "__main__":
    main()
